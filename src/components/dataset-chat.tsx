import { useServerFn } from "@tanstack/react-start";
import { useEffect, useRef, useState } from "react";
import { Send, Sparkles } from "lucide-react";

import { Panel } from "@/components/shell";
import { useCorpus } from "@/lib/corpus-context";
import { askKnowledgeBase } from "@/lib/rag.functions";
import { renderInline } from "@/lib/render-inline";

type Msg = { role: "user" | "assistant"; text: string; failed?: boolean };

const SUGGESTIONS = [
  "Summarize the main complaints about the power grid in these posts",
  "Which accounts are driving the climate conversation?",
  "What is the overall audience mood, and where does it dip?",
];

/**
 * Conversational panel over the active corpus. Every turn re-runs the
 * retrieval engine and asks the generative layer for a cited answer, so the
 * chat stays grounded in the posts the user is currently browsing.
 */
export function DatasetChat() {
  const { retrieve, CORPUS_STATS } = useCorpus();
  const ask = useServerFn(askKnowledgeBase);
  const [messages, setMessages] = useState<Msg[]>([]);
  const [input, setInput] = useState("");
  const [busy, setBusy] = useState(false);
  const scrollRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    scrollRef.current?.scrollTo({ top: scrollRef.current.scrollHeight, behavior: "smooth" });
  }, [messages, busy]);

  async function send(q: string) {
    const question = q.trim();
    if (question.length < 3 || busy) return;
    setBusy(true);
    setInput("");
    setMessages((m) => [...m, { role: "user", text: question }]);
    try {
      const hits = retrieve(question, 6);
      const result = await ask({
        data: {
          question,
          mode: "answer",
          chunks: hits.map((h) => ({ id: h.post.id, text: h.post.chunk })),
        },
      });
      setMessages((m) => [
        ...m,
        {
          role: "assistant",
          text: result.ok ? result.answer : result.error,
          failed: !result.ok,
        },
      ]);
    } catch {
      setMessages((m) => [
        ...m,
        {
          role: "assistant",
          text: "The request could not be completed. Please try again.",
          failed: true,
        },
      ]);
    } finally {
      setBusy(false);
    }
  }

  return (
    <Panel title="Chat with this dataset" hint="Cited answers">
      <div
        ref={scrollRef}
        className="max-h-96 min-h-56 space-y-4 overflow-y-auto pr-1"
        aria-live="polite"
      >
        {messages.length === 0 && !busy && (
          <div className="flex gap-3">
            <span className="mt-0.5 grid size-8 shrink-0 place-items-center rounded-xl bg-primary-subtle text-primary">
              <Sparkles className="h-4 w-4" />
            </span>
            <p className="text-sm text-muted-foreground">
              Ask anything about the {CORPUS_STATS.posts} posts in the current corpus — the answer
              is generated by AI and cites the posts it came from.
            </p>
          </div>
        )}

        {messages.map((m, i) =>
          m.role === "user" ? (
            <div key={i} className="flex justify-end">
              <div className="max-w-[85%] rounded-2xl rounded-br-md bg-primary-subtle px-4 py-2.5 text-sm text-foreground">
                {m.text}
              </div>
            </div>
          ) : (
            <div key={i} className="flex gap-3">
              <span className="mt-0.5 grid size-8 shrink-0 place-items-center rounded-xl bg-primary-subtle text-primary">
                <Sparkles className="h-4 w-4" />
              </span>
              <div
                className={`max-w-[92%] space-y-2 text-sm leading-relaxed ${
                  m.failed ? "text-negative" : "text-foreground"
                }`}
              >
                {m.text
                  .split("\n")
                  .filter(Boolean)
                  .map((line, j) =>
                    line.startsWith("##") ? (
                      <h4 key={j} className="pt-1 text-base font-semibold">
                        {line.replace(/^#+\s*/, "")}
                      </h4>
                    ) : (
                      <p key={j}>
                        {renderInline(line.replace(/^[-*]\s+/, "• "), `${i}-${j}`)}
                      </p>
                    ),
                  )}
              </div>
            </div>
          ),
        )}

        {busy && (
          <div className="flex gap-3">
            <span className="mt-0.5 grid size-8 shrink-0 place-items-center rounded-xl bg-primary-subtle text-primary">
              <Sparkles className="h-4 w-4 animate-pulse" />
            </span>
            <p className="text-sm text-muted-foreground">Reading the corpus…</p>
          </div>
        )}
      </div>

      <div className="mt-4 flex flex-wrap gap-2">
        {SUGGESTIONS.map((s) => (
          <button
            key={s}
            type="button"
            disabled={busy}
            onClick={() => void send(s)}
            className="rounded-full border border-border bg-secondary px-3 py-1.5 text-xs text-muted-foreground transition-colors hover:text-foreground disabled:opacity-50"
          >
            {s}
          </button>
        ))}
      </div>

      <form
        onSubmit={(e) => {
          e.preventDefault();
          void send(input);
        }}
        className="mt-3 flex items-end gap-2"
      >
        <input
          value={input}
          onChange={(e) => setInput(e.target.value)}
          placeholder="Ask a question about this dataset…"
          aria-label="Ask a question about this dataset"
          className="h-10 flex-1 rounded-xl border border-input bg-background px-3 text-sm outline-none focus:border-ring"
        />
        <button
          type="submit"
          disabled={busy || input.trim().length < 3}
          aria-label="Send question"
          className="inline-flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-primary text-primary-foreground transition-colors hover:bg-primary-hover disabled:opacity-50"
        >
          <Send className="h-4 w-4" />
        </button>
      </form>
    </Panel>
  );
}
